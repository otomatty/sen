import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1360, height: 860 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto("http://localhost:4400/index.html");
await page.waitForSelector("[data-testid=app]", { timeout: 30000 });
const w = await page.$("[data-testid=welcome-start]");
if (w) await w.click();
await page.click("[data-testid=nav-team-ENG-issues]");
await page.waitForSelector("[data-testid=issue-row][data-identifier='ENG-20']");
console.log("blocked chip:", await page.locator("[data-testid=issue-row][data-identifier='ENG-20'] [data-testid=blocked-chip]").count());
await page.click("[data-testid=issue-row][data-identifier='ENG-20']");
await page.waitForSelector("[data-testid=relations]");
console.log("relations rows:", await page.locator("[data-testid=relation-row]").count());
await page.screenshot({ path: process.env.OUT + "/demo-relations.png" });
await page.click("[data-testid=nav-help]");
await page.waitForSelector("[data-testid=tutorial-card]");
console.log("tutorial cards:", await page.locator("[data-testid=tutorial-card]").count());
await page.locator("[data-testid=tutorial-card]").nth(13).click();
await page.waitForSelector("[data-testid=tutorial-video]");
await page.waitForTimeout(2500);
console.log("video readyState:", await page.locator("[data-testid=tutorial-video]").evaluate((v) => v.readyState + " " + v.currentSrc.split("/").pop()));
await page.screenshot({ path: process.env.OUT + "/demo-video.png" });
console.log("errors:", errors.slice(0, 5));
await browser.close();
